// ============================================================================

const allGeneratedQuestions = [];
const gradeSummary = {};

for (const [gradeName, gradeData] of Object.entries(GRADE_CURRICULA)) {
  const gradeQuestions = [];
  let gradeCount = 0;

  const civicsTemplates = gradeData.civicsTemplates;
  const financeTemplates = gradeData.financeTemplates;

  // Calculate quota to comfortably exceed 1,000 per grade (target 1,070+)
  const targetCivics = 630;
  const targetFinance = 450;
  const civicsPerTemplate = Math.ceil(targetCivics / civicsTemplates.length);
  const financePerTemplate = Math.ceil(targetFinance / financeTemplates.length);

  // 1. Generate Civics for this grade
  civicsTemplates.forEach((tObj, tIdx) => {
    for (let i = 0; i < civicsPerTemplate; i++) {
      gradeCount++;
      const city = CITIES[(i + tIdx) % CITIES.length];
      const school = SCHOOLS[(i + tIdx) % SCHOOLS.length];
      const name = NAMES[(i + tIdx) % NAMES.length];

      const res = tObj.generator(i, city, school, name);
      const { options, correctIndex } = shuffleOptions(res.correct, res.distractors);

      gradeQuestions.push({
        id: `q-${gradeName.replace(/[^א-ת]/g, '')}-civ-${gradeCount}`,
        subject: 'civics',
        gradeLevel: gradeData.gradeLevel,
        gradeText: gradeName,
        topic: tObj.topic,
        difficulty: i % 3 === 0 ? 'אתגר עליון' : i % 2 === 0 ? 'בגרות' : 'מתקדם',
        question: res.question,
        scenario: res.scenario,
        options: options,
        correctIndex: correctIndex,
        explanation: res.explanation,
        shiraTip: res.shiraTip,
        source: gradeData.gradeLevel === 'senior' 
          ? `פורטל משרד החינוך – אזרחות חט״ע ושאלון בגרות 034281 (${gradeName})`
          : `פורטל משרד החינוך – אזרחות חט״ב תוכנית הלימודים (${gradeName})`
      });
    }
  });

  // 2. Generate Finance for this grade
  financeTemplates.forEach((tObj, tIdx) => {
    for (let i = 0; i < financePerTemplate; i++) {
      gradeCount++;
      const city = CITIES[(i + tIdx) % CITIES.length];
      const school = SCHOOLS[(i + tIdx) % SCHOOLS.length];
      const name = NAMES[(i + tIdx) % NAMES.length];

      const res = tObj.generator(i, city, school, name);
      const { options, correctIndex } = shuffleOptions(res.correct, res.distractors);

      gradeQuestions.push({
        id: `q-${gradeName.replace(/[^א-ת]/g, '')}-fin-${gradeCount}`,
        subject: 'finance',
        gradeLevel: gradeData.gradeLevel,
        gradeText: gradeName,
        topic: tObj.topic,
        difficulty: i % 3 === 0 ? 'אתגר עליון' : i % 2 === 0 ? 'בגרות' : 'מתקדם',
        question: res.question,
        scenario: res.scenario,
        options: options,
        correctIndex: correctIndex,
        explanation: res.explanation,
        shiraTip: res.shiraTip,
        source: `פורטל משרד החינוך – חינוך פיננסי חט״ב ודיני עבודה (${gradeName})`
      });
    }
  });

  gradeSummary[gradeName] = gradeQuestions.length;
  allGeneratedQuestions.push(...gradeQuestions);

  // Save per-grade materials file for teachers & students
  const cleanGrade = gradeName.replace(/[^א-ת]/g, '');
  const gradeMaterialsFile = path.resolve(__dirname, `../materials/grade_${cleanGrade}_comprehensive_1000_plus.json`);
  fs.writeFileSync(gradeMaterialsFile, JSON.stringify(gradeQuestions, null, 2), 'utf-8');
  console.log(`Saved ${gradeQuestions.length} questions for ${gradeName} -> ${gradeMaterialsFile}`);
}

